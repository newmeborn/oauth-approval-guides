import Link from "next/link";
import { GenerateBox } from "@/components/GenerateBox";
import { GuideCard } from "@/components/GuideCard";
import { TierPill } from "@/components/Pills";
import { ACTOR_TEXT, EVIDENCE_TEXT, TIER_MEANING } from "@/lib/guide/format";
import { loadLibrary } from "@/lib/guide/library";
import { TIERS } from "@/lib/guide/tiers";
import { getStore, type StoredGuide } from "@/lib/store";

// Recently generated guides change as people use the generator.
export const revalidate = 60;

export default async function Home() {
  const guides = loadLibrary();
  let recent: StoredGuide[] = [];
  try {
    recent = (await getStore()?.recent(6)) ?? [];
  } catch {
    // The library still works if storage is down.
  }
  return (
    <>
      <section className="hero">
        <h1>Will your OAuth app get approved, and how long will it take?</h1>
        <p>
          Before your agent can act in your users&apos; apps, you register an OAuth app with each provider, and some of them
          review it first. Each guide says how hard that is for the access you need, how much of your time it takes versus how
          long you wait, what blocks approval, and which steps an agent can do for you.
        </p>
        <GenerateBox />
      </section>

      <section id="library" aria-labelledby="library-h">
        <h2 id="library-h">Library</h2>
        <p className="sec-q">
          Researched guides, held to the evidence rules. <Link href="/checks">How I checked them</Link>.
        </p>
        <div className="cards">
          {guides.map((g) => (
            <GuideCard
              key={g.app.slug}
              guide={g}
              href={`/guides/${g.app.slug}`}
              tag={g.provenance.generatedBy === "agent" ? "docs" : "human"}
              foot={`Last checked ${g.provenance.lastChecked}`}
            />
          ))}
        </div>
      </section>

      {recent.length > 0 && (
        <section aria-labelledby="recent-h">
          <h2 id="recent-h">Recently generated by the live agent</h2>
          <p className="sec-q">Written in about a minute from the provider&apos;s own pages; every quote checked against its page.</p>
          <div className="cards">
            {recent.map((r) => (
              <GuideCard key={r.id} guide={r.guide} href={`/g/${r.id}`} tag="generated" foot={`Generated ${r.createdAt.slice(0, 10)}`} />
            ))}
          </div>
        </section>
      )}

      <section aria-labelledby="legend-h" className="legend">
        <h2 id="legend-h">How to read a guide</h2>
        <div className="legend-grid">
          <div>
            <h3>Difficulty tier</h3>
            <p className="muted">Set by the hardest gate an access level must pass, by a fixed rule, never by feel.</p>
            <ul>
              {TIERS.map((t) => (
                <li key={t}>
                  <TierPill tier={t} /> {TIER_MEANING[t]}
                </li>
              ))}
            </ul>
          </div>
          <div>
            <h3>Evidence on every claim</h3>
            <p className="muted">So you know what to double-check.</p>
            <ul>
              {(Object.keys(EVIDENCE_TEXT) as (keyof typeof EVIDENCE_TEXT)[]).map((k) => (
                <li key={k}>
                  <span className={`pill ev ev-${k}`}>{EVIDENCE_TEXT[k].label}</span> {EVIDENCE_TEXT[k].meaning}
                </li>
              ))}
            </ul>
          </div>
          <div>
            <h3>Who does each step</h3>
            <p className="muted">What to hand your coding agent, and what needs you.</p>
            <ul>
              {(Object.keys(ACTOR_TEXT) as (keyof typeof ACTOR_TEXT)[]).map((k) => (
                <li key={k}>
                  <span className={`pill actor actor-${k}`}>{ACTOR_TEXT[k].label}</span> {ACTOR_TEXT[k].meaning}
                </li>
              ))}
            </ul>
          </div>
        </div>
      </section>
    </>
  );
}
